-- V075: work comment mentions follow the comment text. Editing a work comment replaces that comment's
-- work_mention rows (a name taken out of the comment stops waiting on it), so the app role may delete them.
-- A mention row is derived state, like membership and links; work_event keeps the history. Idempotent:
-- granting a privilege the role already holds is a no-op.

GRANT DELETE ON work_mention TO :app_user;
